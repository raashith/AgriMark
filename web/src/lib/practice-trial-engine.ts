export async function createFieldTrial(
  trial: Omit<FieldTrialRecord, 'id' | 'status' | 'safety_approved' | 'created_at'>
): Promise<FieldTrialRecord> {
  const record: FieldTrialRecord = {
    ...trial,
    id: `trial_${Math.random().toString(36).substring(2, 10)}`,
    status: trial.is_ai_draft ? 'PROPOSED' : 'IN_PROGRESS',
    safety_approved: true,
    created_at: new Date().toISOString()
  };

  if (supabaseAdmin) {
    await supabaseAdmin.from('field_trials').insert({
      id: record.id,
      title: record.title,
      crop: record.crop,
      duration_months: record.duration_months,
      status: record.status,
      is_ai_draft: record.is_ai_draft,
      created_at: record.created_at
    });
  }

  return record;
}

export async function submitFarmerContribution(
  userId: string,
  type: UserKnowledgeContribution['contribution_type'],
  title: string,
  content: string
): Promise<UserKnowledgeContribution> {
  const contribution: UserKnowledgeContribution = {
    id: `contrib_${Math.random().toString(36).substring(2, 10)}`,
    user_id: userId,
    contribution_type: type,
    title,
    content,
    status: 'PENDING_REVIEW',
    automatically_validated_as_fact: false,
    created_at: new Date().toISOString()
  };

  if (supabaseAdmin) {
    await supabaseAdmin.from('knowledge_contributions').insert({
      id: contribution.id,
      user_id: contribution.user_id,
      contribution_type: contribution.contribution_type,
      title: contribution.title,
      content: contribution.content,
      status: contribution.status,
      created_at: contribution.created_at
    });
  }

  return contribution;
}
