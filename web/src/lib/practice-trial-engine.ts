import { supabase as supabaseAdmin } from './supabase';

export type ContributionStatus = 'PENDING_REVIEW' | 'VALIDATED' | 'PARTIALLY_VALIDATED' | 'REJECTED' | 'CONTESTED';

export interface AgriculturalPracticeRecord {
  id: string;
  practice_name: string;
  expected_outcome: string;
  evidence_strength: 'HIGH' | 'MODERATE' | 'EMERGING';
  cost_level: 'LOW' | 'MEDIUM' | 'HIGH';
  risk_level: 'LOW' | 'MODERATE' | 'HIGH';
  climate_suitability: string;
  regional_suitability: string;
}

export interface FieldTrialRecord {
  id: string;
  title: string;
  crop: string;
  duration_months: number;
  status: 'PROPOSED' | 'IN_PROGRESS' | 'COMPLETED' | 'VALIDATED';
  is_ai_draft: boolean; // Tagged AI_DRAFT when generated by assistant
  has_control_group: boolean;
  is_farmer_learning_trial: boolean;
  safety_approved: boolean; // Dangerous chemical/biological trials strictly blocked
  created_at: string;
}

export interface UserKnowledgeContribution {
  id: string;
  user_id: string;
  contribution_type: 'OBSERVATION' | 'PHOTO' | 'FIELD_RESULT' | 'FARMER_PRACTICE' | 'LOCAL_KNOWLEDGE';
  title: string;
  content: string;
  status: ContributionStatus;
  automatically_validated_as_fact: false; // Never auto-promoted to scientific fact
  created_at: string;
}

